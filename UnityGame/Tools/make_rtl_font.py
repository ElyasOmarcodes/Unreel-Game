#!/usr/bin/env python3
"""
Prepares Vazirmatn (OFL) for Unity's simple text renderer, which cannot join Arabic-script
letters by itself: every letter form the font has (isolated, initial, medial, final) gets its own
code point in the Private Use Area, and a C# table tells the in-game shaper (Rtl.cs) which code to
use for which form. Covers Pashto, Dari/Persian, Arabic and Urdu letters.

Run:  python3 UnityGame/Tools/make_rtl_font.py <Vazirmatn-Bold.ttf>   (needs fonttools)
"""
import os
import sys
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_FONT = os.path.join(HERE, "..", "Assets", "Resources", "Fonts", "Vazirmatn-UA.ttf")
OUT_CS = os.path.join(HERE, "..", "Assets", "Scripts", "Core", "RtlTable.cs")
PUA = 0xE000
FORMS = ["isol", "init", "medi", "fina"]


def single_subst_maps(font, feature_tag):
    """glyph -> glyph for one GSUB feature (single substitutions, through extensions)."""
    gsub = font["GSUB"].table
    result = {}
    lookups = set()
    for rec in gsub.FeatureList.FeatureRecord:
        if rec.FeatureTag == feature_tag:
            lookups.update(rec.Feature.LookupListIndex)
    for index in sorted(lookups):
        lookup = gsub.LookupList.Lookup[index]
        for sub in lookup.SubTable:
            if lookup.LookupType == 7:
                sub = sub.ExtSubTable
            mapping = getattr(sub, "mapping", None)
            if mapping and lookup.LookupType in (1, 7) and all(isinstance(v, str) for v in mapping.values()):
                for k, v in mapping.items():
                    result.setdefault(k, v)
    return result


def main():
    font = TTFont(sys.argv[1])
    cmap = font.getBestCmap()
    maps = {f: single_subst_maps(font, f) for f in FORMS}
    letters = [c for c in list(range(0x0621, 0x064B)) + list(range(0x066E, 0x06D4)) if c in cmap]
    table = []          # (char, isol, init, medi, fina)
    new_cmap = {}
    code = PUA
    for c in letters:
        base = cmap[c]
        forms = []
        for f in FORMS:
            glyph = maps[f].get(base, base if f == "isol" else None)
            if glyph is None:
                forms.append(0)
                continue
            new_cmap[code] = glyph
            forms.append(code)
            code += 1
        table.append((c, *forms))
    # add the new code points to every Unicode cmap subtable
    for sub in font["cmap"].tables:
        if sub.isUnicode():
            if sub.format == 4 and code > 0xFFFF:
                continue
            sub.cmap.update(new_cmap)
    font["name"].setName("Vazirmatn UA", 1, 3, 1, 0x409)
    os.makedirs(os.path.dirname(OUT_FONT), exist_ok=True)
    font.save(OUT_FONT)

    rows = ",\n".join(
        f"            0x{c:04X}, 0x{a:04X}, 0x{b:04X}, 0x{m:04X}, 0x{f:04X}" for c, a, b, m, f in table)
    with open(OUT_CS, "w", encoding="utf-8") as out:
        out.write(f"""// Generated by UnityGame/Tools/make_rtl_font.py from Vazirmatn (OFL). Do not edit.
namespace UA
{{
    public static partial class Rtl
    {{
        /// <summary>Per letter: code point, then the private-use codes of its isolated, initial, medial and final forms (0 = none).</summary>
        private static readonly int[] Forms =
        {{
{rows}
        }};
    }}
}}
""")
    print(f"{len(table)} letters, {len(new_cmap)} forms -> {OUT_FONT}")


if __name__ == "__main__":
    main()
